import { test, expect } from "@playwright/test";
test("Focus discussion creates a real Action, reads it back, and survives project navigation", async ({ page }) => {
  const session = (await page.context().cookies()).find(c => c.name === "pm_session");
  expect(session).toBeTruthy();
  const headers = { Authorization: "Bearer " + session!.value };
  const caps = await page.request.get("/api/conversations/capabilities", { headers });
  expect(caps.ok(), await caps.text()).toBe(true);
  test.skip(!(await caps.json()).enabled, "FOCUS_AGENT_ENABLED is off in the legacy regression run");
  const title = "Focus 协作 " + Date.now();
  const created = await page.request.post("/api/projects", { headers, data: { title, description: "独立隔离的焦点协作端到端验证项目", goal: "核对实验资料并推进", scenario: "RESEARCH" } });
  expect(created.ok(), await created.text()).toBe(true);
  const project = (await created.json()).project;
  await page.goto("/focus");
  const panel = page.getByRole("region", { name: "问忆程", exact: true });
  await expect(panel).toBeVisible();
  await expect(panel.getByText("正在读取讨论…")).toHaveCount(0);
  await panel.getByRole("button", { name: "新讨论", exact: true }).click();
  await expect(panel.getByRole("textbox", { name: "与忆程讨论项目" })).toBeVisible();
  await panel.getByRole("textbox", { name: "与忆程讨论项目" }).fill("帮我先处理“" + title + "”最重要的待办。");
  await panel.getByRole("button", { name: "发送", exact: true }).click();
  await expect(panel.getByRole("button", { name: "确认创建行动", exact: true })).toBeVisible();
  const response = page.waitForResponse(r => r.url().includes("/proposals/") && r.url().endsWith("/confirm"));
  await panel.getByRole("button", { name: "确认创建行动", exact: true }).click();
  const receipt = await (await response).json();
  expect(receipt.actionId).toBeTruthy();
  await expect(panel.getByText(/已创建行动 · 待办/)).toBeVisible();
  await panel.getByRole("link", { name: "查看原结果", exact: true }).click();
  await expect(page).toHaveURL(new RegExp("/projects/" + project.id + "/actions.*conversation="));
  await expect(page.locator("#action-" + receipt.actionId)).toBeVisible();
  await page.getByRole("navigation", { name: "项目主要导航" }).getByRole("link", { name: "资料", exact: true }).click();
  await page.getByRole("navigation", { name: "资料功能" }).getByRole("link", { name: "项目记忆与问答", exact: true }).click();
  await expect(page).toHaveURL(/\/knowledge\?conversation=/);
  await expect(page.getByRole("region", { name: "问忆程", exact: true }).getByText(/已创建行动 · 待办/)).toBeVisible();
  await page.getByRole("link", { name: "返回原焦点讨论", exact: true }).click();
  await expect(page).toHaveURL(/\/focus\?conversation=/);
  await expect(panel.getByText(/已创建行动 · 待办/)).toBeVisible();
  await page.screenshot({ path: "evidence/focus-agent/F2/20261026-local/focus-desktop.png", fullPage: true });
  await panel.getByRole("button", { name: "记录与查看结果", exact: true }).click();
  const work = panel.getByRole("region", { name: "原任务协作", exact: true });
  await expect(work.getByRole("textbox", { name: "实际完成结果" })).toBeVisible();
  await work.getByRole("textbox", { name: "实际完成结果" }).fill("核对了实验资料与部署条件，本轮检查通过，真机测试仍待补充。");
  await work.getByRole("button", { name: "预览完成与复盘" }).click();
  await panel.getByRole("button", { name: "确认此操作", exact: true }).click();
  await expect(panel.getByText(/行动已完成，复盘已保存/)).toBeVisible();
  await page.screenshot({ path: "evidence/focus-agent/F2/20261026-local/focus-collaboration.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: "evidence/focus-agent/F2/20261026-local/focus-mobile.png", fullPage: true });
  const actions = await page.request.get("/api/projects/" + project.id + "/actions", { headers });
  const originals = (await actions.json()).actions.filter((a: {id:string}) => a.id === receipt.actionId);
  expect(originals).toHaveLength(1); expect(originals[0].status).toBe("DONE"); expect(originals[0].resultCardId).toBeTruthy();
});
test("Focus compares frozen options and resumes the same original Mission inside the conversation", async ({ page }) => {
  const session = (await page.context().cookies()).find(c => c.name === "pm_session")!;
  const headers = { Authorization: "Bearer " + session.value };
  const caps = await page.request.get("/api/conversations/capabilities", { headers });
  expect(caps.ok()).toBe(true); test.skip(!(await caps.json()).enabled, "Focus flag is off in legacy regression");
  const created = await page.request.post("/api/projects", { headers, data: { title: "F2 方案接续 " + Date.now(), description: "独立测试方案选择与原任务接续", goal: "核对部署证据", scenario: "RESEARCH" } });
  expect(created.ok()).toBe(true); const project = (await created.json()).project;
  const mr = await page.request.post("/api/missions", { headers, data: { projectId: project.id, requestId: crypto.randomUUID(), goal: "核对部署证据" } });
  expect(mr.ok(), await mr.text()).toBe(true); const mission = (await mr.json()).mission;
  expect((await page.request.post("/api/missions/" + mission.id + "/pause", { headers, data: { requestId: "pause", expectedVersion: mission.version } })).ok()).toBe(true);
  const cr = await page.request.post("/api/conversations", { headers, data: { requestId: crypto.randomUUID(), scope: "PROJECT", projectId: project.id } });
  expect(cr.ok()).toBe(true); const id = (await cr.json()).id;
  const read = await page.request.get("/api/conversations/" + id, { headers }); const cv = await read.json();
  expect((await page.request.post("/api/conversations/" + id + "/turns", { headers, data: { requestId: "inspect", expectedVersion: cv.version, message: "查已有证据", entityRef: { kind: "MISSION", id: mission.id, projectId: project.id } } })).ok()).toBe(true);
  await page.goto("/focus?conversation=" + id);
  const panel = page.getByRole("region", { name: "问忆程", exact: true });
  await panel.getByRole("button", { name: "在此协作", exact: true }).first().click();
  const work = panel.getByRole("region", { name: "原任务协作", exact: true });
  await work.getByText("对比推进方案", { exact: true }).click();
  await work.getByRole("spinbutton", { name: "可用时间（分钟）" }).fill("60");
  await work.getByRole("spinbutton", { name: "交付所需（分钟）" }).fill("20");
  await work.getByRole("button", { name: "生成方案对比", exact: true }).click();
  await expect(work.getByText("先核对变化依据", { exact: true })).toBeVisible();
  await work.getByText("先核对变化依据", { exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "evidence/focus-agent/F2/20261026-local/focus-scenarios.png", fullPage: true });
  await panel.getByRole("textbox", { name: "与忆程讨论项目" }).fill("选第一种");
  await panel.getByRole("button", { name: "发送", exact: true }).click();
  await panel.getByRole("button", { name: "确认此操作", exact: true }).click();
  await expect(panel.getByText(/已采用原方案；原委托保留/)).toBeVisible();
  await work.getByRole("button", { name: "预览接续原委托", exact: true }).click();
  const resumed = page.waitForResponse(r => r.url().includes("/proposals/") && r.url().endsWith("/confirm"));
  await panel.getByRole("button", { name: "确认此操作", exact: true }).click();
  const resumeResponse = await resumed;
  expect(resumeResponse.ok(), await resumeResponse.text()).toBe(true);
  const detail = await page.request.get("/api/missions/" + mission.id, { headers });
  expect(detail.ok()).toBe(true); const value = await detail.json();
  expect(value.mission.id).toBe(mission.id); expect(value.mission.status).toBe("READY");
  const list = await page.request.get("/api/missions?projectId=" + project.id, { headers });
  expect((await list.json()).missions).toHaveLength(1);
});
