import { chromium } from "playwright";
const BASE = "http://127.0.0.1:34111";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "zh-CN" });
const page = await context.newPage();
const requests = [];
page.on("request", (r) => requests.push({ url: r.url(), type: r.resourceType(), t: Date.now() }));
await page.goto(BASE + "/", { waitUntil: "networkidle" });
await page.waitForTimeout(800);
const facade = page.locator("button[aria-label*='Bilibili 官方播放器']").first();
await facade.scrollIntoViewIfNeeded();
await facade.click();
await page.waitForTimeout(4000);
const collapseAt = Date.now();
await page.locator("button", { hasText: "收起播放器" }).first().click();
await page.waitForTimeout(2500);
const afterCollapse = requests.filter((r) => r.t > collapseAt && /bilibili|bilivideo|b23\.tv/i.test(r.url));
const beforeCollapse = requests.filter((r) => r.t <= collapseAt && /bilibili|bilivideo|b23\.tv/i.test(r.url));
console.log(JSON.stringify({ totalRequests: requests.length, bilibiliBeforeCollapse: beforeCollapse.length, bilibiliAfterCollapse: afterCollapse.length, afterCollapseRequests: afterCollapse.map((r) => ({ type: r.type, url: r.url.slice(0, 140) })), iframeStillPresent: await page.evaluate(() => !!document.querySelector("iframe")), activeElement: await page.evaluate(() => ({ tag: document.activeElement.tagName.toLowerCase(), ariaLabel: document.activeElement.getAttribute("aria-label") })) }, null, 1));
await browser.close();
