import { afterAll, beforeAll, expect, it, vi } from "vitest";
import { continuityDatabase } from "./helpers/continuityDatabase";
const isolated = continuityDatabase("s0-capability");
let db: typeof import("@/lib/db").db;
beforeAll(async () => { db = (await import("@/lib/db")).db; });
afterAll(async () => { await db.$disconnect(); vi.unstubAllEnvs(); vi.restoreAllMocks(); void isolated; });
const input = { title: "合成原子建项", goal: "仅验证服务合同", description: "独立库中的建项与模型模式回归", scenario: "RESEARCH" as const, deadline: null };
it("Project、OWNER 和原请求回执同事务；丢失回包重试不重复创建", async () => {
  const { createOwnedProject } = await import("@/lib/repositories/projects");
  const user = await db.user.create({ data: { username: "s0-owner", displayName: "合成用户", passwordHash: "unused" } });
  const [a, b] = await Promise.all([createOwnedProject(input, user.id, "stable-create"), createOwnedProject(input, user.id, "stable-create")]);
  expect(a.project.id).toBe(b.project.id);
  expect([a.replayed, b.replayed].sort()).toEqual([false, true]);
  expect(await db.projectMembership.count({ where: { projectId: a.project.id, userId: user.id, role: "OWNER" } })).toBe(1);
  await expect(createOwnedProject({ ...input, goal: "不同内容" }, user.id, "stable-create")).rejects.toMatchObject({ code: "IDEMPOTENCY_CONFLICT" });
  await expect(createOwnedProject({ ...input, title: "不可留下的孤儿项目" }, "missing-user", "failed" )).rejects.toBeDefined();
  expect(await db.project.count({ where: { title: "不可留下的孤儿项目" } })).toBe(0);
});
it("能力查询不调用模型：缺 key、规则模式和配额耗尽均不可用", async () => {
  const { cloudCapability } = await import("@/lib/auth/cloudCapability");
  const network = vi.spyOn(globalThis, "fetch");
  const user = await db.user.findUniqueOrThrow({ where: { username: "s0-owner" } });
  vi.stubEnv("LLM_MODE", "mock");
  expect(await cloudCapability(user.id)).toMatchObject({ available: false, reason: "RULE_MODE", networkHealth: "UNTESTED" });
  vi.stubEnv("LLM_MODE", "openai-compatible"); vi.stubEnv("LLM_API_KEY", "");
  expect(await cloudCapability(user.id)).toMatchObject({ available: false, reason: "NOT_CONFIGURED" });
  vi.stubEnv("LLM_API_KEY", "synthetic-not-a-real-key");
  await db.accountSecurity.create({ data: { userId: user.id, email: "synthetic@example.invalid", emailVerifiedAt: new Date(), dailyCloudLimit: 1 } });
  await db.accountCloudUsage.create({ data: { userId: user.id, day: new Intl.DateTimeFormat("sv-SE", { timeZone: "Asia/Shanghai" }).format(new Date()), used: 1 } });
  expect(await cloudCapability(user.id)).toMatchObject({ available: false, reason: "DAILY_QUOTA_EXHAUSTED", remainingToday: 0 });
  expect(network).not.toHaveBeenCalled();
  network.mockRestore();
});
it("规则与失败后备模式持久读回，幂等重放不把规则成功升级为实模成功", async () => {
  vi.stubEnv("LLM_MODE", "mock");
  const project = await db.project.findFirstOrThrow({ where: { title: input.title } });
  const { processCaptureWithRequest } = await import("@/lib/services/captureService");
  const first = await processCaptureWithRequest(project.id, "原始实验记录需要核对对照条件", "实验记录", { requestId: "rule" });
  expect(first.card.processing).toMatchObject({ mode: "RULE", provider: "mock" });
  const replay = await processCaptureWithRequest(project.id, "原始实验记录需要核对对照条件", "实验记录", { requestId: "rule" });
  expect(replay.replayed).toBe(true);
  expect(replay.card.processing).toEqual(first.card.processing);
  vi.stubEnv("LLM_MODE", "openai-compatible"); vi.stubEnv("LLM_API_KEY", "synthetic-not-a-real-key");
  const provider = vi.spyOn(await import("@/lib/agent/llmAgent"), "structureWithLLMWithMeta").mockRejectedValue(new Error("synthetic-provider-timeout"));
  const fallback = await processCaptureWithRequest(project.id, "另一次实验未获得可靠模型响应", "实验记录", { requestId: "fallback" });
  expect(fallback.card.processing).toMatchObject({ mode: "FALLBACK", provider: "mock-fallback" });
  expect((await db.capture.findUniqueOrThrow({ where: { id: fallback.card.captureId! } })).processingJson).toMatchObject({ mode: "FALLBACK" });
  provider.mockRestore();
});
